#define CANSUB_WEBSOCKET_FIN (0x80)
#define CANSUB_WEBSOCKET_RSV (0x70)
#define CANSUB_WEBSOCKET_OPCODE (0x0F)
#define CANSUB_WEBSOCKET_MASKED (0x80)
#define CANSUB_WEBSOCKET_LENGTH (0x7F)

/* Payload length markers in the second header byte. */
#define CANSUB_WEBSOCKET_LENGTH_16 (126)
#define CANSUB_WEBSOCKET_LENGTH_64 (127)

/* Largest header without the masking key (16 bit payload length). */
#define CANSUB_WEBSOCKET_HEADER_MAX (4)

_Static_assert(CANSUB_WEBSOCKET_SHA1_SIZE == PSA_HASH_LENGTH(PSA_ALG_SHA_1), "Sec-WebSocket-Accept is based on SHA-1");
_Static_assert(CANSUB_WEBSOCKET_KEY_LENGTH == 24, "A Sec-WebSocket-Key is 24 characters (RFC 6455)");
_Static_assert(CANSUB_WEBSOCKET_ACCEPT_LENGTH == 28, "A Sec-WebSocket-Accept is 28 characters (RFC 6455)");

