cansub_result cansub_websocket_key_generate(char *key, size_t key_size)
{
    uint8_t nonce[CANSUB_WEBSOCKET_NONCE_SIZE];
    size_t length = 0;

    cansub_result const result = cansub_transport_result_from_mbedtls(psa_generate_random(nonce, sizeof(nonce)), CANSUB_RESULT_ERROR);
    if (result != CANSUB_RESULT_OK)
    {
        return result;
    }

    /* Encoding only fails if the buffer is too small for the key, which is a bug. */
    return (mbedtls_base64_encode((unsigned char *)key, key_size, &length, nonce, sizeof(nonce)) == 0) ? CANSUB_RESULT_OK : CANSUB_RESULT_ERROR;
}

cansub_result cansub_websocket_accept_compute(char const *key, char *accept, size_t accept_size)
{
    static char const guid[] = "258EAFA5-E914-47DA-95CA-C5AB0DC85B11";
    uint8_t input[CANSUB_WEBSOCKET_KEY_LENGTH + sizeof(guid) - 1];
    uint8_t hash[CANSUB_WEBSOCKET_SHA1_SIZE];
    size_t hash_length = 0;
    size_t accept_length = 0;
    size_t const key_length = strlen(key);

    if (key_length != CANSUB_WEBSOCKET_KEY_LENGTH)
    {
        /* The key is generated by cansub_websocket_key_generate(), so another length is a bug. */
        return CANSUB_RESULT_ERROR;
    }

    memcpy(input, key, key_length);
    memcpy(input + key_length, guid, sizeof(guid) - 1);

    cansub_result const result = cansub_transport_result_from_mbedtls(psa_hash_compute(PSA_ALG_SHA_1, input, sizeof(input), hash, sizeof(hash), &hash_length), CANSUB_RESULT_ERROR);
    if (result != CANSUB_RESULT_OK)
    {
        return result;
    }

    /* Encoding only fails if the buffer is too small for the accept value, which is a bug. */
    return (mbedtls_base64_encode((unsigned char *)accept, accept_size, &accept_length, hash, hash_length) == 0) ? CANSUB_RESULT_OK : CANSUB_RESULT_ERROR;
}

cansub_result cansub_websocket_mask_generate(uint8_t mask[CANSUB_WEBSOCKET_MASK_SIZE])
{
    return cansub_transport_result_from_mbedtls(psa_generate_random(mask, CANSUB_WEBSOCKET_MASK_SIZE), CANSUB_RESULT_ERROR);
}

size_t cansub_websocket_frame_size(size_t payload_size)
{
    size_t const header_size = (payload_size < CANSUB_WEBSOCKET_LENGTH_16) ? 2 : 4;

    return header_size + CANSUB_WEBSOCKET_MASK_SIZE + payload_size;
}

cansub_result cansub_websocket_write_frame(cansub_ringbuffer *ringbuffer, cansub_websocket_opcode opcode, uint8_t const mask[CANSUB_WEBSOCKET_MASK_SIZE], void const *payload, size_t payload_size)
{
    assert(ringbuffer);
    assert(mask);
    assert(payload || !payload_size);

    cansub_result result = CANSUB_RESULT_ERROR;

    do
    {
        if (payload_size > CANSUB_WEBSOCKET_PAYLOAD_MAX)
        {
            result = CANSUB_RESULT_INVALID_ARG;
            break;
        }

        if (cansub_ringbuffer_space(ringbuffer) < cansub_websocket_frame_size(payload_size))
        {
            result = CANSUB_RESULT_AGAIN;
            break;
        }

        /* Header and masking key. */
        uint8_t header[CANSUB_WEBSOCKET_HEADER_MAX + CANSUB_WEBSOCKET_MASK_SIZE];
        size_t header_size = 0;

        header[header_size++] = CANSUB_WEBSOCKET_FIN | (uint8_t)opcode;
        if (payload_size < CANSUB_WEBSOCKET_LENGTH_16)
        {
            header[header_size++] = CANSUB_WEBSOCKET_MASKED | (uint8_t)payload_size;
        }
        else
        {
            header[header_size++] = CANSUB_WEBSOCKET_MASKED | CANSUB_WEBSOCKET_LENGTH_16;
            header[header_size++] = (uint8_t)(payload_size >> 8);
            header[header_size++] = (uint8_t)payload_size;
        }
        memcpy(&header[header_size], mask, CANSUB_WEBSOCKET_MASK_SIZE);
        header_size += CANSUB_WEBSOCKET_MASK_SIZE;

        (void)cansub_ringbuffer_write(ringbuffer, header, header_size);

        /* Masked payload, written directly into the free spans. */
        cansub_ringbuffer_spans const spans = cansub_ringbuffer_spans_write(ringbuffer);
        uint8_t const *source = payload;
        uint8_t *span_1 = spans.span_1;
        uint8_t *span_2 = spans.span_2;

        for (size_t i = 0; i < payload_size; i++)
        {
            uint8_t const byte = source[i] ^ mask[i % CANSUB_WEBSOCKET_MASK_SIZE];

            if (i < spans.span_1_size)
            {
                span_1[i] = byte;
            }
            else
            {
                span_2[i - spans.span_1_size] = byte;
            }
        }
        cansub_ringbuffer_commit_write(ringbuffer, payload_size);

        result = CANSUB_RESULT_OK;
    } while (0);

    return result;
}

void cansub_websocket_rx_reset(cansub_websocket_rx *rx)
{
    rx->payload_remaining = 0;
    rx->in_message = false;
}

cansub_result cansub_websocket_read(cansub_websocket_rx *rx, cansub_ringbuffer *ringbuffer, void *buffer, size_t buffer_size)
{
    uint8_t *const destination = buffer;
    size_t copied = 0;

    while (true)
    {
        if (rx->payload_remaining == 0)
        {
            /* Parse the next header. */
            uint8_t header[CANSUB_WEBSOCKET_HEADER_MAX];
            uint32_t const available = cansub_ringbuffer_peek(ringbuffer, header, sizeof(header));
            if (available < 2)
            {
                break;
            }

            bool const fin = (header[0] & CANSUB_WEBSOCKET_FIN) != 0;
            uint8_t const opcode = header[0] & CANSUB_WEBSOCKET_OPCODE;
            uint32_t length = header[1] & CANSUB_WEBSOCKET_LENGTH;
            uint32_t header_size = 2;

            if ((header[0] & CANSUB_WEBSOCKET_RSV) || (header[1] & CANSUB_WEBSOCKET_MASKED))
            {
                /* No extensions are negotiated, and the server must not mask. */
                return CANSUB_RESULT_CONNECTION_PROTOCOL;
            }
            if (length == CANSUB_WEBSOCKET_LENGTH_64)
            {
                return CANSUB_RESULT_CONNECTION_PROTOCOL;
            }
            if (length == CANSUB_WEBSOCKET_LENGTH_16)
            {
                if (available < 4)
                {
                    break;
                }
                length = ((uint32_t)header[2] << 8) | header[3];
                header_size = 4;
            }

            if (opcode == CANSUB_WEBSOCKET_OPCODE_CLOSE)
            {
                /* Control frames are never fragmented and carry at most 125 bytes. */
                if (!fin || (header_size != 2))
                {
                    return CANSUB_RESULT_CONNECTION_PROTOCOL;
                }
                if (copied > 0)
                {
                    /* Deliver the data before the close. */
                    break;
                }
                if (length == 1)
                {
                    /* The body is empty, or a 2 byte status code followed by an optional UTF-8 reason. One byte is neither. */
                    return CANSUB_RESULT_CONNECTION_PROTOCOL;
                }
                if (cansub_ringbuffer_size(ringbuffer) < header_size + length)
                {
                    break;
                }

                /* The close code and reason are not used. */
                cansub_ringbuffer_commit_read(ringbuffer, header_size + length);
                rx->in_message = false;
                return CANSUB_RESULT_CLOSED;
            }
            else if (opcode == CANSUB_WEBSOCKET_OPCODE_BINARY)
            {
                if (rx->in_message)
                {
                    return CANSUB_RESULT_CONNECTION_PROTOCOL;
                }
            }
            else if (opcode == CANSUB_WEBSOCKET_OPCODE_CONTINUATION)
            {
                if (!rx->in_message)
                {
                    return CANSUB_RESULT_CONNECTION_PROTOCOL;
                }
            }
            else
            {
                return CANSUB_RESULT_CONNECTION_PROTOCOL;
            }

            cansub_ringbuffer_commit_read(ringbuffer, header_size);
            rx->in_message = !fin;
            rx->payload_remaining = length;
            continue;
        }

        if (copied == buffer_size)
        {
            break;
        }

        cansub_result const bytes = cansub_ringbuffer_read(ringbuffer, destination + copied, MIN(buffer_size - copied, rx->payload_remaining));
        if (bytes <= 0)
        {
            break;
        }

        copied += (size_t)bytes;
        rx->payload_remaining -= (uint32_t)bytes;
    }

    return (cansub_result)copied;
}

