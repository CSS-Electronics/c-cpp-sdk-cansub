#define CANSUB_STREAM_MAX 2
_Static_assert(CANSUB_STREAM_MAX == CANSUB_STREAM_CONTROL + 1, "CANSUB_STREAM_MAX must follow the last stream");

/** Longest host in the options, without the NUL terminator. */
#define CANSUB_HOST_MAX 255

/** Length of a device ID (8 hex digits), without the NUL terminator. */
#define CANSUB_DEVICE_ID_LENGTH 8

/** An API version as cansub_api_version_check() reports it: MAJOR in the upper 16 bits, MINOR in the lower 16 bits. */
#define CANSUB_API_VERSION_MAKE(major, minor) (((uint32_t)(major) << 16) | (uint32_t)(minor))

/** Supported CANsub API version, "05.00". */
#define CANSUB_API_VERSION CANSUB_API_VERSION_MAKE(5, 0)

/** Sample points are given in 0.01 %, so this is 100 %. */
#define CANSUB_SAMPLE_POINT_SCALE (10000u)

/* Context state masks for CANSUB_STATE_IN(). */
#define CANSUB_CTX_MASK_INVALID     CANSUB_STATE_BIT(CANSUB_STATE_INVALID)
#define CANSUB_CTX_MASK_INITIALIZED CANSUB_STATE_BIT(CANSUB_STATE_INITIALIZED)
#define CANSUB_CTX_MASK_OPENING     CANSUB_STATE_BIT(CANSUB_STATE_OPENING)
#define CANSUB_CTX_MASK_OPEN        CANSUB_STATE_BIT(CANSUB_STATE_OPEN)
#define CANSUB_CTX_MASK_CLOSING     CANSUB_STATE_BIT(CANSUB_STATE_CLOSING)
#define CANSUB_CTX_MASK_CLOSED      CANSUB_STATE_BIT(CANSUB_STATE_CLOSED)

/** Opening or open, the close has not started. */
#define CANSUB_CTX_MASK_ACTIVE      (CANSUB_CTX_MASK_OPENING | CANSUB_CTX_MASK_OPEN)
/** Closing or closed, no new requests or opens are accepted. */
#define CANSUB_CTX_MASK_ENDING      (CANSUB_CTX_MASK_CLOSING | CANSUB_CTX_MASK_CLOSED)

/* The public enum has no COUNT, so its highest value is checked instead. Update this when a state is added. */
_Static_assert(CANSUB_STATE_CLOSED < 32, "Too many states");

/***********************************************************************************************************************
 * Private type definitions.
 **********************************************************************************************************************/

struct cansub_ctx
{
    cansub_state state;

    /** Flag indicating if cansub_data_eof() was called for the data stream.
     * It will never request a new transport. */
    bool data_finished;

    /** Remote channel. */
    uint32_t channel;

    /** Verified instead of the host if set, see cansub_verify_certificate(). Empty if not set. */
    char device_id[CANSUB_DEVICE_ID_LENGTH + 1];
    /** Host the glue connects to, the TLS server name and the HTTP Host. Always set. */
    char host[CANSUB_HOST_MAX + 1];
    /** Without a device ID, verify only the chain to the root, see cansub_verify_certificate(). */
    bool accept_any_device;

    cansub_transport transports[CANSUB_STREAM_MAX];
    cansub_stream_obj *streams[CANSUB_STREAM_MAX];

    cansub_stream_control stream_control;
    cansub_stream_data stream_data;

    struct
    {
        mbedtls_x509_crt ca_chain;

        /** TLS configuration of the transports using these credentials. */
        mbedtls_ssl_config ssl_config;

        /** Client certificate, optionally followed by intermediate certificates. */
        mbedtls_x509_crt client_certificate;

        /** Private key of the client certificate. */
        mbedtls_pk_context client_key;
    } tls;
};

