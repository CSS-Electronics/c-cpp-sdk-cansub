static int cansub_verify_certificate(void *user_data, mbedtls_x509_crt *certificate, int depth, uint32_t *flags)
{
    cansub_ctx const *const ctx = user_data;

    /* Only the device certificate is checked against a name. The chain to the root is always verified. */
    if (depth == 0)
    {
        if (ctx->device_id[0] != '\0')
        {
            /* The device ID replaces the host, e.g. for an IPv4 address or a custom DNS name. */
            *flags &= ~MBEDTLS_X509_BADCERT_CN_MISMATCH;

            if (!cansub_certificate_matches_device(certificate, ctx->device_id))
            {
                *flags |= MBEDTLS_X509_BADCERT_CN_MISMATCH;
            }
        }
        else if (ctx->accept_any_device)
        {
            /* Any device signed by the root is accepted. */
            *flags &= ~MBEDTLS_X509_BADCERT_CN_MISMATCH;
        }
    }

    return 0;
}

static bool cansub_certificate_matches_device(mbedtls_x509_crt const *certificate, char const *device_id)
{
    bool matches = false;

    /* The device certificate lists "<device ID>-usb.local" and "<device ID>-eth.local", so checking the first is enough. */
    char hostname[CANSUB_DEVICE_ID_LENGTH + sizeof("-usb.local")];
    snprintf(hostname, sizeof(hostname), "%s-usb.local", device_id);

    for (mbedtls_x509_sequence const *san = &certificate->subject_alt_names; san != NULL; san = san->next)
    {
        bool const is_dns_name = ((san->buf.tag & MBEDTLS_ASN1_TAG_VALUE_MASK) == MBEDTLS_X509_SAN_DNS_NAME);

        if (is_dns_name && (cansub_strcasecmp_sized(hostname, (char const *)san->buf.p, san->buf.len) == 0))
        {
            matches = true;
            break;
        }
    }

    return matches;
}

static bool cansub_api_version_parse(char const *version, size_t version_size, uint32_t *remote)
{
    assert(remote);

    bool result = false;
    char const *version_start = version;

    do
    {
        /* Only the exact forms XX.YY (5 bytes) and "XX.YY" (7 bytes) are accepted, nothing around them. */
        if ((version_size > 0) && (version[0] == '"'))
        {
            if (version_size != 7)
            {
                break;
            }
            if (version[6] != '"')
            {
                break;
            }
            version_start = version + 1;
        }
        else if (version_size != 5)
        {
            break;
        }

        /* Ensure the decimal point is placed correctly. */
        if (version_start[2] != '.')
        {
            break;
        }

        /* Ensure that all the other characters are digits. */
        if (!cansub_ascii_isdigit(version_start[0]))
        {
            break;
        }
        if (!cansub_ascii_isdigit(version_start[1]))
        {
            break;
        }
        if (!cansub_ascii_isdigit(version_start[3]))
        {
            break;
        }
        if (!cansub_ascii_isdigit(version_start[4]))
        {
            break;
        }

        uint16_t const major = (version_start[0] - '0') * 10 + (version_start[1] - '0');
        uint16_t const minor = (version_start[3] - '0') * 10 + (version_start[4] - '0');

        *remote = CANSUB_API_VERSION_MAKE(major, minor);

        result = true;
    } while (0);

    return result;
}

static cansub_result cansub_options_check(cansub_context_options const *options, mbedtls_x509_crt *certificate, mbedtls_pk_context *key, cansub_options_faults *faults)
{
    cansub_result result = CANSUB_RESULT_ERROR;
    cansub_options_faults found = 0;

    do
    {
        if (options->struct_size != sizeof(*options))
        {
            /* We have chosen to not be backwards compatible. The other fields cannot be read safely. */
            found |= CANSUB_OPTIONS_FAULT_STRUCT_SIZE;
            result = CANSUB_RESULT_OK;
            break;
        }

        if (!options->host)
        {
            /* The host is always required, the device ID only changes what is verified. */
            found |= CANSUB_OPTIONS_FAULT_HOST_MISSING;
        }
        if (options->device_id && ((strlen(options->device_id) != CANSUB_DEVICE_ID_LENGTH) || !cansub_ascii_is_hex_str(options->device_id)))
        {
            /* The device ID must be 8 hex digits. */
            found |= CANSUB_OPTIONS_FAULT_DEVICE_ID;
        }
        if (options->host && (!cansub_ascii_is_host_str(options->host) || (options->host[0] == '\0') || (strlen(options->host) > CANSUB_HOST_MAX)))
        {
            /* The host must be a DNS name or an IPv4 address, and fit inside the context. */
            found |= CANSUB_OPTIONS_FAULT_HOST;
        }
        if (options->channel == 0)
        {
            /* Channel must be at least 1. */
            found |= CANSUB_OPTIONS_FAULT_CHANNEL;
        }

        if ((!options->client_certificate && options->client_certificate_size) ||
            (!options->client_key && options->client_key_size) ||
            (options->client_certificate && !options->client_key) ||
            (options->client_key && !options->client_certificate))
        {
            /* The mTLS certificate and key are only used as a pair. */
            found |= CANSUB_OPTIONS_FAULT_MTLS_PAIR;
        }
        else if (options->client_certificate && options->client_key)
        {
            int mbed_status = mbedtls_x509_crt_parse(certificate, options->client_certificate, options->client_certificate_size);
            cansub_result const certificate_result = cansub_transport_result_from_mbedtls(mbed_status, CANSUB_RESULT_INVALID_ARG);
            if (certificate_result == CANSUB_RESULT_MEMORY)
            {
                result = CANSUB_RESULT_MEMORY;
                break;
            }
            if (certificate_result != CANSUB_RESULT_OK)
            {
                found |= CANSUB_OPTIONS_FAULT_MTLS_CERTIFICATE;
            }

            mbed_status = mbedtls_pk_parse_key(key, options->client_key, options->client_key_size, NULL, 0);
            cansub_result const key_result = cansub_transport_result_from_mbedtls(mbed_status, CANSUB_RESULT_INVALID_ARG);
            if (key_result == CANSUB_RESULT_MEMORY)
            {
                result = CANSUB_RESULT_MEMORY;
                break;
            }
            if (key_result != CANSUB_RESULT_OK)
            {
                found |= CANSUB_OPTIONS_FAULT_MTLS_KEY;
            }

            /* The pair can only be checked if both parse. */
            if ((certificate_result == CANSUB_RESULT_OK) && (key_result == CANSUB_RESULT_OK))
            {
                mbed_status = mbedtls_pk_check_pair(&certificate->pk, key);
                cansub_result const pair_result = cansub_transport_result_from_mbedtls(mbed_status, CANSUB_RESULT_INVALID_ARG);
                if (pair_result == CANSUB_RESULT_MEMORY)
                {
                    result = CANSUB_RESULT_MEMORY;
                    break;
                }
                if (pair_result != CANSUB_RESULT_OK)
                {
                    found |= CANSUB_OPTIONS_FAULT_MTLS_MISMATCH;
                }
            }
        }

        result = CANSUB_RESULT_OK;
    } while (0);

    if (result == CANSUB_RESULT_OK)
    {
        *faults = found;
    }

    return result;
}

static void cansub_pump(cansub_ctx *ctx, cansub_stream stream)
{
    cansub_transport *const transport = &ctx->transports[stream];
    cansub_stream_obj *const stream_obj = ctx->streams[stream];

    bool progress = true;

    while(progress)
    {
        progress = false;

        cansub_tls_status const status = cansub_transport_progress(transport);
        if (status != CANSUB_TLS_ESTABLISHED)
        {
            if (status == CANSUB_TLS_FAILED)
            {
                (void) cansub_stream_apply(stream_obj, transport, CANSUB_RESULT_CONNECTION_TLS);
            }
            break;
        }

        cansub_ringbuffer *const tx = cansub_stream_tx_source(stream_obj);
        if (tx)
        {
            cansub_result result = cansub_transport_write(transport, tx);
            if (result > 0)
            {
                progress = true;
                result = cansub_stream_tx_done(stream_obj);
            }
            else if (result == CANSUB_RESULT_AGAIN)
            {
                result = CANSUB_RESULT_OK;
            }

            if (cansub_stream_apply(stream_obj, transport, result))
            {
                /* E.g. the close of the remote has been answered, or a TLS failure. */
                break;
            }
        }

        cansub_ringbuffer *const rx = cansub_stream_rx_sink(stream_obj);
        if (rx)
        {
            cansub_result result = cansub_transport_read(transport, rx);
            if (result > 0)
            {
                progress = true;
                result = cansub_stream_rx_done(stream_obj);
            }
            else if (result == CANSUB_RESULT_AGAIN)
            {
                result = CANSUB_RESULT_OK;
            }
            else if (result == 0)
            {
                /* Defensive: a read of nothing without AGAIN means the TLS layer saw the transport end. */
                result = CANSUB_RESULT_CONNECTION_TLS;
            }

            if (cansub_stream_apply(stream_obj, transport, result))
            {
                /* E.g. a response with Connection: close, a close from the remote, or a fatal error. */
                break;
            }
        }
    }

    /* A response may have completed the last outstanding request. */
    cansub_update_state(ctx);
}

static bool cansub_stream_apply(cansub_stream_obj *stream_obj, cansub_transport *transport, cansub_result result)
{
    if (result == CANSUB_RESULT_OK)
    {
        return false;
    }

    if (result != CANSUB_RESULT_CLOSED)
    {
        cansub_stream_failed(stream_obj, result);
    }

    /* The stream is done with this transport. */
    cansub_transport_close(transport);

    return true;
}

static void cansub_update_state(cansub_ctx *ctx)
{
    cansub_stream_data const *const data = &ctx->stream_data;

    if (CANSUB_STATE_IN(ctx->state, CANSUB_CTX_MASK_OPENING) && cansub_stream_data_is_open(data))
    {
        ctx->state = CANSUB_STATE_OPEN;
    }

    /* A fatal data stream error, a close from the remote, or the remote ending the data transport (TLS close_notify)
     * closes the context. While active, the data transport is otherwise only closed together with one of the others. */
    bool const data_ending = (cansub_stream_data_error(data) != CANSUB_RESULT_OK) || cansub_stream_data_remote_closed(data) ||
                             cansub_transport_is_closing(&ctx->transports[CANSUB_STREAM_DATA]);
    if (data_ending && CANSUB_STATE_IN(ctx->state, CANSUB_CTX_MASK_ACTIVE))
    {
        ctx->state = CANSUB_STATE_CLOSING;
    }

    if (!ctx->data_finished)
    {
        /* Data link not finished yet, so no cross stream dependencies. */
        return;
    }

    cansub_transport *const control_transport = &ctx->transports[CANSUB_STREAM_CONTROL];
    cansub_stream_obj *const control_stream = ctx->streams[CANSUB_STREAM_CONTROL];

    /* Nothing is left to abort, an abort already written still gets its response. */
    cansub_stream_control_abort_cancel(&ctx->stream_control);

    /* Shut the control link down once the data stream has finished and no requests are outstanding. */
    if (cansub_transport_is_connected(control_transport) && !cansub_stream_wants_transport(control_stream))
    {
        cansub_transport_close(control_transport);
    }

    /* CLOSED once the data stream has finished and the control link is down. */
    ctx->state = cansub_transport_is_idle(control_transport) ? CANSUB_STATE_CLOSED : CANSUB_STATE_CLOSING;
}

static cansub_result cansub_response_none(cansub_ctx const *ctx)
{
    bool const closing = CANSUB_STATE_IN(ctx->state, CANSUB_CTX_MASK_ENDING);
    /* The abort of cansub_close_force() never yields a response, only requests count. */
    bool const in_flight = cansub_stream_control_requests_outstanding(&ctx->stream_control);

    return (closing && !in_flight) ? CANSUB_RESULT_CLOSED : CANSUB_RESULT_AGAIN;
}

static size_t cansub_error_message(cansub_ctx const *ctx, cansub_result error, char *message, size_t message_size)
{
    cansub_http_response const *const upgrade = &ctx->stream_data.upgrade_response;
    int length;

    switch (error)
    {
        case CANSUB_RESULT_OK:
        {
            length = snprintf(message, message_size, "No error");
            break;
        }
        case CANSUB_RESULT_CONNECTION_REJECTED:
        {
            if (upgrade->header_size != 0)
            {
                length = snprintf(message, message_size, "The WebSocket upgrade was rejected with HTTP status %" PRIu32, upgrade->status);
            }
            else
            {
                length = snprintf(message, message_size, "The WebSocket upgrade was rejected");
            }
            break;
        }
        case CANSUB_RESULT_CONNECTION_TLS:
        {
            length = cansub_error_message_tls(&ctx->transports[CANSUB_STREAM_DATA], message, message_size);
            break;
        }
        case CANSUB_RESULT_CONNECTION_PROTOCOL:
        {
            length = snprintf(message, message_size, "Invalid WebSocket upgrade response, or a WebSocket protocol violation by the remote");
            break;
        }
        case CANSUB_RESULT_CONNECTION_LOST:
        {
            length = snprintf(message, message_size, "The remote closed the WebSocket, or the transport was lost, closed or could not be opened before the close completed");
            break;
        }
        case CANSUB_RESULT_MEMORY:
        {
            length = snprintf(message, message_size, "Out of memory while processing the data stream");
            break;
        }
        default:
        {
            length = snprintf(message, message_size, "Internal error (%" PRId32 ")", error);
            break;
        }
    }

    if (length < 0)
    {
        message[0] = '\0';
        return 0;
    }

    /* snprintf() reports the untruncated length. */
    return MIN((size_t)length, message_size - 1);
}

static int cansub_error_message_tls(cansub_transport const *transport, char *message, size_t message_size)
{
    int const tls_error = transport->tls_error;

    if (tls_error == 0)
    {
        return snprintf(message, message_size, "TLS error");
    }

    char reason[128];
    mbedtls_strerror(tls_error, reason, sizeof(reason));

    int length = snprintf(message, message_size, "TLS error: %s (-0x%04X)", reason, (unsigned int)-tls_error);

    /* Name the failed certificate checks, e.g. a device certificate which does not match. */
    uint32_t const verify_flags = mbedtls_ssl_get_verify_result(&transport->ssl_context);
    if ((tls_error == MBEDTLS_ERR_X509_CERT_VERIFY_FAILED) && (verify_flags != 0) && (verify_flags != UINT32_MAX) &&
        (length >= 0) && ((size_t)length < message_size))
    {
        /* One line per failed check, each as " <reason>\n". Joined as " <reason>; <reason>". */
        char info[256];
        int const info_length = mbedtls_x509_crt_verify_info(info, sizeof(info), " ", verify_flags);

        if (info_length > 0)
        {
            size_t end = strlen(info);
            while ((end > 0) && (info[end - 1] == '\n'))
            {
                info[--end] = '\0';
            }
            for (size_t i = 0; i < end; i++)
            {
                if (info[i] == '\n')
                {
                    info[i] = ';';
                }
            }

            int const extra = snprintf(message + length, message_size - (size_t)length, ":%s", info);
            length = (extra < 0) ? length : length + extra;
        }
    }

    return length;
}

static bool cansub_calculate_bittiming_for_phase(cansub_bittiming_segment *segment, cansub_bittiming_limits const *limits, uint32_t bitrate, uint32_t samplepoint)
{
    /* tq is the time per bit, or 1 + segment1 + segment2.
     * A given bitrate is given by the CAN clock divided by the prescaler and the number of time quanta each bit takes.
     * So bitrate = clock / (brp * tq) = clock / (brp * (1 + segment1 + segment2)).
     * The target bitrate and clock is fixed, so only the prescaler and the number of time quanta each bit takes can vary.
     */

    uint64_t bitrate_error_best = UINT64_MAX;
    uint64_t samplepoint_error_best = UINT64_MAX;
    uint64_t actual_bitrate_best = 0;
    uint64_t tq_best = 0;
    uint32_t brp_best = UINT32_MAX;

    for (uint32_t brp = limits->brp_min; brp <= limits->brp_max; brp += limits->brp_inc)
    {
        /* Determine how many time quanta we have at this prescaler, rounding to the nearest number. */
        uint64_t const div = (uint64_t)brp * (uint64_t)bitrate;
        uint64_t const tq = (limits->clock + div / 2) / div;

        /* Ensure the number of quanta is within our limits. */
        if (tq < (1 + limits->seg1_min + limits->seg2_min))
        {
            /* tq only gets smaller with a larger prescaler, so no later one fits either. Break the loop. */
            break;
        }
        if (tq > (1 + limits->seg1_max + limits->seg2_max))
        {
            /* tq can only be smaller from here on out, continue the loop. */
            continue;
        }

        /* Determine the actual bitrate and the error. */
        uint64_t const actual_bitrate = (uint64_t)brp * tq * bitrate;
        uint64_t const bitrate_error = ABS_DIFF(actual_bitrate, limits->clock);
        if ((bitrate_error * 1000) > actual_bitrate)
        {
            /* Outside the targeted 0.1 % error. */
            continue;
        }

        /* Calculate the segments from the sample point. */
        uint64_t const sample_tq = (samplepoint * tq + (CANSUB_SAMPLE_POINT_SCALE / 2)) / CANSUB_SAMPLE_POINT_SCALE;   /* 1 + seg1. */
        uint64_t const seg1_raw = (sample_tq > 0) ? (sample_tq - 1) : 0;
        uint64_t const seg1_clamp_lower = MAX(limits->seg1_min, tq - 1 - MIN(tq - 1, limits->seg2_max));
        uint64_t const seg1_clamp_upper = MIN(limits->seg1_max, tq - 1 - limits->seg2_min);
        uint64_t seg1_clamped = CLAMP(seg1_raw, seg1_clamp_lower, seg1_clamp_upper);
        uint64_t const samplepoint_error = ABS_DIFF(samplepoint * tq, (1 + seg1_clamped) * CANSUB_SAMPLE_POINT_SCALE);

        if (brp_best != UINT32_MAX)
        {
            /* Relative errors, cross-multiplied. Bitrate first, then sample point. Ties keep the smaller prescaler. */
            uint64_t const rate_new = bitrate_error * actual_bitrate_best;
            uint64_t const rate_best = bitrate_error_best * actual_bitrate;
            if (rate_new > rate_best)
            {
                continue;
            }
            if ((rate_new == rate_best) && ((samplepoint_error * tq_best) >= (samplepoint_error_best * tq)))
            {
                continue;
            }
        }
        bitrate_error_best = bitrate_error;
        samplepoint_error_best = samplepoint_error;
        actual_bitrate_best = actual_bitrate;
        tq_best = tq;
        brp_best = brp;
        segment->brp = brp;
        segment->seg1 = (uint32_t)seg1_clamped;
        segment->seg2 = (uint32_t)(tq - (seg1_clamped + 1));
    }

    if (brp_best != UINT32_MAX)
    {
        segment->sjw = MIN(MIN(segment->seg1, segment->seg2), limits->sjw_max);
    }

    return (brp_best != UINT32_MAX);
}

/* The name of each code is its identifier, so the names cannot drift from the header. */
#define CANSUB_NAME_CASE(code) case code: return #code

static char const *cansub_result_code_name(cansub_result code)
{
    switch (code)
    {
        CANSUB_NAME_CASE(CANSUB_RESULT_OK);
        CANSUB_NAME_CASE(CANSUB_RESULT_AGAIN);
        CANSUB_NAME_CASE(CANSUB_RESULT_MEMORY);
        CANSUB_NAME_CASE(CANSUB_RESULT_INVALID_ARG);
        CANSUB_NAME_CASE(CANSUB_RESULT_CLOSED);
        CANSUB_NAME_CASE(CANSUB_RESULT_INVALID_STATE);
        CANSUB_NAME_CASE(CANSUB_RESULT_CONNECTION_REJECTED);
        CANSUB_NAME_CASE(CANSUB_RESULT_CONNECTION_TLS);
        CANSUB_NAME_CASE(CANSUB_RESULT_CONNECTION_PROTOCOL);
        CANSUB_NAME_CASE(CANSUB_RESULT_CONNECTION_LOST);
        CANSUB_NAME_CASE(CANSUB_RESULT_NOT_FOUND);
        CANSUB_NAME_CASE(CANSUB_RESULT_NOT_SUPPORTED);
        CANSUB_NAME_CASE(CANSUB_RESULT_ERROR);
        default:
        {
            return NULL;
        }
    }
}

static char const *cansub_state_code_name(cansub_state state)
{
    switch (state)
    {
        CANSUB_NAME_CASE(CANSUB_STATE_INVALID);
        CANSUB_NAME_CASE(CANSUB_STATE_INITIALIZED);
        CANSUB_NAME_CASE(CANSUB_STATE_OPENING);
        CANSUB_NAME_CASE(CANSUB_STATE_OPEN);
        CANSUB_NAME_CASE(CANSUB_STATE_CLOSING);
        CANSUB_NAME_CASE(CANSUB_STATE_CLOSED);
        default:
        {
            return NULL;
        }
    }
}

#undef CANSUB_NAME_CASE

static cansub_result cansub_name_copy(char const *name, char *buffer, size_t buffer_size)
{
    size_t const size = strlen(name) + 1;

    if (buffer_size >= size)
    {
        memcpy(buffer, name, size);
    }

    return (cansub_result)size;
}
